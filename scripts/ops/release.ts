#!/usr/bin/env bun
/**
 * The whole manual release sequence, so the tree it leaves behind is correct
 * without a human remembering a step.
 *
 * IT IS TWO PHASES, AND THE SPLIT IS FORCED BY A RULESET. `main-require-pr` now
 * carries `bypass_actors: []` — nothing reaches `main` outside a pull request,
 * permanently. The single `release:manual` this replaces ended in `bumpp`, which
 * commits, tags AND pushes STRAIGHT TO `main`; that push is now rejected, and
 * rejected AFTER the bump, the changelog write and the local tag, i.e. on the
 * irreversible side of the flow. So:
 *
 *   release:prepare vX.Y.Z   guard, pin, gate 4, gate 5, changelog, bump,
 *                            rebuild, commit on `release/vX.Y.Z`, push the
 *                            BRANCH, open the PR. CUTS NO TAG.
 *   release:tag vX.Y.Z       once that PR has merged: fetch, assert the merged
 *                            manifest reads X.Y.Z and that the tip IS the
 *                            release commit, on the tree you are standing on,
 *                            re-run gate 4, cut the ANNOTATED tag on the merged
 *                            HEAD, push it.
 *
 * THE TAG CANNOT BE CUT IN PHASE A, and that is what makes this two commands
 * rather than one flag. A squash merge rewrites the SHA, so a tag created on the
 * branch would point at a commit that never reaches `main`. It has to be created
 * after the merge, against `main`'s actual merged HEAD — which is what every one
 * of phase B's assertions is about. Only the release COMMIT ever needed the
 * bypass: both rulesets are `target: branch` and there is no tag ruleset, so
 * `git push origin vX.Y.Z` is unrestricted.
 *
 * THIS IS A STRENGTHENING, NOT A WORKAROUND. Under the direct-push flow the
 * release commit was the ONE commit that reached `main` completely unverified —
 * the bump, the regenerated `dist/` and the generated changelog all landed with
 * no check run against them. It now passes `test`, `windows` and `gate` like
 * every other commit, and `bindings:check` inside `test` is precisely the gate
 * that catches the stale `dist/` this file was written for.
 *
 * PUBLISHING IS `publish-package.yml`, which fires on the tag phase B pushes and
 * runs `bun publish` against the GitHub Package Registry. CI pins the Bun
 * version by construction, so the tarball cannot be built by whatever the
 * releaser happens to have on PATH — and that is why `--no-publish` is a no-op
 * rather than a switch (see `NO_PUBLISH_FLAG`). `prepack.ts` still guards the
 * pin, both for that workflow and for anyone running `bun publish` or
 * `bun pm pack` by hand.
 *
 * `release:manual` was `release:preflight && bumpp && bun publish --access
 * public`. Two things were missing from it, and they turn out to be the same
 * thing twice:
 *
 *   1. `bun build` INLINES `package.json` (`BUILD_VERSION` in
 *      `src/lib/update/build-info.ts` falls back to `packageJson.version`), and
 *      `bumpp` bumps that version. So every release left the COMMITTED
 *      `dist/main.js` describing the previous version and `bindings:check` red
 *      on `main` until someone regenerated by hand. Measured, same Bun 1.3.11,
 *      one bumped version: `85697a48…` at `0.3.2` vs `2e541596…` at `0.3.3`.
 *      v0.3.2 and v0.4.0 were both rebuilt by hand after the fact.
 *   2. Nothing asserted a clean working tree, so an unrelated in-flight edit
 *      could be swept into the release commit and shipped under the tag.
 *
 * A third thing was missing, and it is the same thing a third time: the
 * CHANGELOG entry. The runbook used to say "generate the block with
 * `release:notes vX.Y.Z` and paste it into `CHANGELOG.md`" and then, in the very
 * next step, "run `release:manual`" — whose FIRST action is the clean-tree guard
 * above, which refuses any tracked modification, the freshly pasted changelog
 * included. Step 3 guaranteed step 4 would refuse. v0.4.1 was cut around it by
 * committing the changelog separately first, which is why its history carries
 * two commits where every release before it carries one. So this file writes the
 * entry itself: the tag is an argument to it, `release-notes.ts` is a sibling,
 * and `CHANGELOG.md` carries an insertion anchor put there for exactly this.
 * The guard keeps its zero exemptions — see WHERE THE CHANGELOG IS WRITTEN.
 *
 * WHY A WRAPPER RATHER THAN JUST `bumpp -x`. `bumpp`'s execute hook is the right
 * PLACE for the rebuild — it runs after `updateFiles` and before `gitCommit`
 * (`versionBump()` in `bumpp/dist/shared/*.mjs`), which is the only window where
 * the new version is on disk and the commit has not happened yet. But `-x` alone
 * is not sufficient, because of how `bumpp` commits. Its default `gitCommit` is:
 *
 *     git commit --allow-empty --message <msg> <the files bumpp itself updated>
 *
 * That is git's PATHSPEC form, and `git commit <pathspec>` deliberately IGNORES
 * THE INDEX for every other path. So a hook that does the documented fix —
 * `git add -f dist/main.js` — has its work silently dropped from the release
 * commit and left dangling after it, which is the exact state this file exists
 * to prevent. Measured on a throwaway repo, staging `dist/main.js` and then
 * committing `bumpp`-style:
 *
 *     A: git commit -m … package.json     → git show HEAD:dist/main.js = v1  (stale)
 *                                           git status              = `M  dist/main.js`
 *     B: git commit -m … --all            → git show HEAD:dist/main.js = v2  (correct)
 *                                           git status              = clean
 *
 * `--all` is what makes `bumpp` commit the INDEX rather than a pathspec, so the
 * hook's `git add -f` lands. (`-a` stages tracked modifications ON TOP OF the
 * index; anything already added — including a brand-new content-hash chunk that
 * `-a` would never have picked up on its own — stays.)
 *
 * AND `--all` IS EXACTLY WHAT DISABLES `bumpp`'S OWN CLEAN-TREE CHECK. From its
 * CLI:
 *
 *     if (!options.all && !options.noGitCheck) await checkGitStatus()
 *
 * — and `noGitCheck` defaults to `true` regardless, so `bumpp` checks nothing
 * today and would check nothing under the flag the rebuild needs. The rebuild
 * fix and the clean-tree guard are therefore not two independent chores: turning
 * on the first removes the only backstop that could have supplied the second.
 * Something has to own the ordering — guard, then pin, then bump, then tag —
 * and a `&&` chain in `package.json` cannot express "guard the tree that the
 * step after next is allowed to modify". Hence this file.
 *
 * WHAT COUNTS AS CLEAN, AND WHY (see `cleanTreeObjection`). Blocking: every
 * TRACKED modification, staged or unstaged, including `dist/`. Non-blocking:
 * untracked files.
 *
 *   - Tracked, including `dist/`: `git commit --all` sweeps every tracked
 *     modification into the release commit, so those bytes ship under the tag
 *     with no gate having seen them. `dist/` is force-tracked against
 *     `.gitignore`, so a hand-edited or half-built `dist/` is a tracked
 *     modification like any other — and `bindings:check` reads the INDEX, not
 *     the working tree, so it is structurally blind to it. This guard is the
 *     only thing in the repo that looks.
 *   - It does not fight the rebuild, because of WHERE it runs: the guard is step
 *     one of this file, and the rebuild happens later, inside `bumpp`'s execute
 *     hook. By the time `dist/` is touched the guard has already passed. The
 *     guard's demand is "`dist/` matched `HEAD` when we started", which is true
 *     of every tree the previous release left behind.
 *   - Untracked files do NOT block. The mechanism being guarded is `git commit
 *     --all`, which stages only tracked paths; an untracked file cannot reach
 *     the release commit by any route in this flow. Blocking on one would fail
 *     the release for a scratch note or an editor artifact — a false positive on
 *     a path whose next step is irreversible. They are listed as a note instead,
 *     so a releaser who expected a file to ship finds out before the tag rather
 *     than after. (Ignored files are not listed by `git status --porcelain` at
 *     all, so nothing under an untouched `dist/` shows up here.)
 *
 * WHY THE TAG IS AN ARGUMENT (`release:prepare vX.Y.Z`). The changelog block
 * is generated from the GitHub milestone whose title IS the tag, so the notes
 * cannot be fetched — and a bad milestone cannot be refused — until the version
 * is known. Letting `bumpp` prompt for it would push both after the bump. The
 * milestone model already decides the tag in advance (`release:check milestone
 * vX.Y.Z`, `release:notes vX.Y.Z`), so naming it once more here takes nothing
 * away, and the version reaches `bumpp` as `--release X.Y.Z`, which makes gate 3
 * — "the tag matches `package.json`" — true by construction rather than by a
 * preflight anyone can skip. That is the failure `v0.1.1` shipped.
 *
 * WHERE THE CHANGELOG IS WRITTEN, AND WHY IT IS NOT AN EXEMPTION. The block is
 * FETCHED, VALIDATED AND RENDERED before `bumpp` — so a milestone that
 * `release:notes` would refuse to emit for (missing, empty, an unparseable PR
 * title, an unmerged PR) refuses the whole release at exit 1, with the tree
 * still exactly as the guard found it. It is WRITTEN inside `bumpp`'s execute
 * hook, beside the rebuild, for the same reason the rebuild is there: that is
 * the only window where the commit has not happened yet, and `git commit --all`
 * is about to sweep the working tree into it. The hook therefore produces
 * everything the release commit carries beyond the version bump itself.
 *
 * Two consequences worth stating, because both are the point:
 *
 *   - The guard is untouched and still has NO exemptions. `CHANGELOG.md` is
 *     dirty for the same reason `dist/` is: this script dirtied it, after the
 *     guard, deliberately. The guard only ever asked "did the tree match HEAD
 *     when we started".
 *   - Nothing is written on any refusal path, and nothing is written before the
 *     `bumpp` confirmation prompt. Declining that prompt (`process.exit(1)` in
 *     `bumpp`'s CLI) or hitting Ctrl-C leaves the tree clean, so the next
 *     attempt is not blocked by the leftovers of the last one — which is the
 *     failure mode of pasting the block by hand, mechanised.
 *
 * The rendered block reaches the hook through the environment
 * (`MAXIMAL_RELEASE_CHANGELOG_BLOCK`), because the hook is a separate process
 * `bumpp` spawns with the ambient environment. A temp file would work too and
 * costs an untracked artefact in the one flow that reports untracked files. With
 * the variable unset — a by-hand `release.ts --rebuild` — the hook rebuilds and
 * stages `dist/` and touches no markdown, exactly as it did before.
 *
 * THAT HANDOVER DEPENDS ON `realRunner` PASSING `env` EXPLICITLY, and it did not
 * until this change. Bun's `spawnSync` defaults the child's environment to the
 * SNAPSHOT the process started with, not to the current `process.env`, so a
 * variable set at runtime is dropped without a word. Measured, Bun 1.3.11:
 *
 *     process.env.PROBE = "set-by-parent"
 *     spawnSync(bun, ["-e", …])                        → PROBE undefined
 *     spawnSync(bun, ["-e", …], { env: process.env })  → PROBE set-by-parent
 *
 * Caught in a scratch clone, where the first end-to-end release came out green
 * with no changelog entry in the commit. `prepack.ts`'s `realRunner` now names
 * `env`, and `prepack.test.ts` pins it — it is the one test in that suite that
 * spawns anything, because the failure it prevents is silent and green.
 *
 * AN ENTRY THAT IS ALREADY THERE IS LEFT ALONE. If `CHANGELOG.md` already has a
 * `## X.Y.Z` heading for the version being cut — a re-run, or a human who pasted
 * it — the changelog step is skipped in full, including the `gh` reads. It is
 * reported, not refused: the entry the release needs exists, and rewriting
 * somebody's hand-edited block (or appending a second one) is the only outcome
 * worse than leaving it.
 *
 * THE REBUILD USES `process.execPath`, NEVER A BARE `bun` — the trap
 * `scripts/ops/prepack.ts` documents, re-measured for the `bun run` path this
 * script is launched through:
 *
 *     $ ~/.bun/bin/bun run probe        # outer interpreter: 1.3.11, the pin
 *     execPath      : /opt/homebrew/Cellar/bun/1.3.10/bin/bun
 *     versions.bun  : 1.3.14
 *
 * i.e. invoking the pinned binary and letting the script say `bun` gets you the
 * developer's Bun, and `bun build`'s output is a function of the Bun version. So
 * the rebuild goes through `prepack()`, which bundles with `process.execPath` —
 * the same binary whose `process.versions.bun` was checked, with no PATH lookup
 * in between. For the same reason the execute hook is spawned as
 * `"<process.execPath>" "<this file>" --rebuild` rather than `bun run …`:
 * `bumpp` spawns it with the ambient PATH, so naming the binary is the only way
 * to know which one bundles.
 *
 * THE PIN ASSERTION STILL MEASURES THE RIGHT PROCESS. `release:preflight`'s
 * guarantee was that it is launched by the same bare `bun` that `prepack` will
 * later get; this file is launched the same way (`bun run release:prepare`), so
 * asserting on its own `process.versions.bun` is the identical measurement. It
 * delegates to `prepack({ checkOnly: true })` so the refusal text stays in one
 * place. Phase B does not re-assert it: it builds nothing, and the bytes it
 * tags were built by phase A and re-verified by `bindings:check` on the PR.
 *
 * WHAT IS STAGED comes from `check-bindings.ts`'s `ARTIFACTS`, not a literal
 * list, so the set this stages cannot drift from the set `bindings:check`
 * verifies. `-f` is not optional: `dist/` is gitignored, so a bare `git add`
 * silently skips a NEW file (a renamed content-hash chunk).
 *
 * Usage:
 *   bun run release:prepare vX.Y.Z    # guard, pin, gates, notes, bump+rebuild,
 *                                     #   branch, push, PR — no tag
 *   bun run release:prepare vX.Y.Z -y # anything else goes to bumpp
 *   bun run release:tag vX.Y.Z        # after that PR merges: tag main, push it
 *   bun scripts/ops/release.ts --rebuild   # just rebuild + stage dist/
 *
 * Exit codes: 0 ok · 1 refused · 2 a step failed, including a gate that could
 * not READ what it compares against. Phase A refuses on no tag, a dirty tree, an
 * off-pin Bun, a tag that already exists or is not ahead of every tag that does,
 * a PR still open in the milestone being cut, a milestone the notes cannot be
 * generated from, or a `release/vX.Y.Z` branch that is already there. Phase B
 * refuses on a merged manifest that is not X.Y.Z, a merged head that is not the
 * release commit itself, a checkout that is not standing on that merged commit
 * with a clean tree, or gate 4. Every phase-A refusal is ahead of the branch and
 * `bumpp`; every phase-B refusal is ahead of `git tag`.
 *
 * TWO OF THOSE REFUSALS ARE `release-gates.ts`, CALLED FROM HERE. Gate 4 (the
 * tag is ahead of every tag that exists, local AND remote) and gate 5 (nothing
 * that claims to ship in this release is still open) are both checks about the
 * instant the tag is cut, so a preflight a human runs and a workflow that fires
 * on tag push are respectively skippable and too late. Gate 4 therefore runs in
 * BOTH phases: cheap early refusal in `prepare()`, and again in `tagRelease()`
 * because the PR may have sat open long enough for another agent to push the tag
 * this one is about. See `evaluateTagOrder` and `evaluateOpenPrs`.
 *
 * `git` and every child process go through the two injectable runners this repo
 * already uses (`check-bindings.ts`'s `GitRunner`, `prepack.ts`'s
 * `CommandRunner`), the GitHub reads go through `release-notes.ts`'s `GhRunner`,
 * and `CHANGELOG.md` is read and written through an injected pair — so the tests
 * run offline without a bundler, a repository, a registry or a working copy.
 */

